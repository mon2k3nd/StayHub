  /// Trả về phí của tiện ích khớp với [keyPrefix].
  ///
  /// LƯU Ý: tiện ích có thể có nhiều tên gọi khác nhau tuỳ danh mục
  /// (vd: "Wifi/Internet", "Internet", "Wifi"; "Bãi để xe", "Giữ xe";
  /// "Vệ sinh", "Rác"). Hàm này khớp theo nhiều tiền tố và ưu tiên
  /// tiện ích có giá > 0 để tránh trường hợp khớp nhầm một tiện ích
  /// miễn phí cùng nhóm khiến phí bị lưu thành 0 ("Miễn phí").
  ///
  /// [fallbackCtrl] là ô nhập giá riêng (Internet/Gửi xe/Rác) — dùng khi
  /// người dùng nhập giá ở ô chuyên biệt thay vì cấu hình tiện ích.
  double getAmenityFee(
    String keyPrefix, {
    TextEditingController? fallbackCtrl,
  }) {
    final prefixes = keyPrefix
        .split('|')
        .map((e) => e.trim().toLowerCase())
        .where((e) => e.isNotEmpty)
        .toList();

    double best = 0.0;
    if (prefixes.isNotEmpty) {
      try {
        for (final entry in _selectedAmenities.entries) {
          final name = entry.key.toLowerCase();
          final matches = prefixes.any((p) => name.contains(p));
          if (!matches) continue;
          // Tôn trọng `chargeType`: tiện ích "free" không được tính vào phí,
          // kể cả khi payload còn sót `price` > 0.
          final chargeType = (entry.value['chargeType'] ?? 'free').toString();
          if (chargeType == 'free') continue;
          final price = (entry.value['price'] ?? 0.0).toDouble();
          // Ưu tiên giá lớn nhất (bỏ qua tiện ích miễn phí cùng nhóm).
          if (price > best) best = price;
        }
      } catch (_) {}
    }

    // Fallback: ô nhập giá chuyên biệt (nếu có và lớn hơn).
    if (fallbackCtrl != null) {
      final raw = fallbackCtrl.text
          .replaceAll(',', '')
          .replaceAll('.', '')
          .trim();
      final v = double.tryParse(raw) ?? 0.0;
      if (v > best) best = v;
    }
    return best;
  }

