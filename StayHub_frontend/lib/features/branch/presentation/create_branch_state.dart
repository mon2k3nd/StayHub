  // ignore: unused_element
  double _calculateProgress() {
    int totalRequired = 7;
    int filled = 0;

    // Bước 1: Thông tin cơ bản (4 trường)
    if (_nameCtrl.text.trim().isNotEmpty) filled++;
    if (_addressDetailCtrl.text.trim().isNotEmpty) filled++;
    // Địa chỉ cũ: Tỉnh/Huyện/Xã
    if (_selectedDistrict63Province != null &&
        _selectedDistrict63 != null &&
        _selectedWard63 != null) {
      filled++;
    }
    if (_coverPhotos.isNotEmpty) filled++;

    // Bước 2: Mô hình kinh doanh (1 trường)
    if (_catSelectedByUser) filled++;

    // Bước 5: Tài chính (1 trường gộp)
    if (_elecPriceCtrl.text.isNotEmpty && _waterPriceCtrl.text.isNotEmpty) {
      filled++;
    }

    // Bước 3: Quy mô (1 trường — chỉ tính với mô hình vận hành theo phòng)
    final bool needsRoomConfig =
        rentalCategoryById(_catId)?.isRoomBased ?? false;
    if (needsRoomConfig) {
      totalRequired++;
      final floors = int.tryParse(_floorsCtrl.text);
      final rpf = int.tryParse(_roomsPerFloorCtrl.text);
      if (floors != null && floors >= 1 && rpf != null && rpf > 0) filled++;
    }

    if (totalRequired == 0) return 0.0;
    return (filled / totalRequired).clamp(0.0, 1.0);
  }

