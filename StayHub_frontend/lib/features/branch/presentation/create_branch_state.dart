  void _onBranchCodeTextChanged() {
    final current = _branchCodeCtrl.text;
    if (current.isEmpty) return;
    if (current != _lastAutoAssignedCode && !_isBranchCodeManuallyEdited) {
      setState(() => _isBranchCodeManuallyEdited = true);
    }
  }

  void _onBranchCodeChanged() {
    final prefix = _branchCodeCtrl.text.isNotEmpty
        ? _branchCodeCtrl.text
        : 'CN';
    // Update room codes based on new prefix (single source of truth).
    _resyncRoomCodes();
    for (int i = 0; i < _sharedWcs.length; i++) {
      final wc = _sharedWcs[i];
      final newCode = '${prefix}_${wc.tempId}';
      if (wc.code != newCode) {
        wc.code = newCode;
      }
    }
    _updateProgress();
  }

  /// Kiểm tra trùng mã dãy trọ bất đồng bộ với debounce 600ms
  void _checkBranchCodeDebounced(String code) {
    _codeCheckTimer?.cancel();
    if (code.isEmpty) {
      setState(() {
        _isBranchCodeTaken = false;
        _isCheckingCode = false;
      });
      return;
    }
    setState(() => _isCheckingCode = true);
    _codeCheckTimer = Timer(const Duration(milliseconds: 600), () async {
      try {
        final ds = ref.read(branchRemoteDataSourceProvider);
        final taken = await ds.checkBranchCodeTaken(
          code,
          excludeId: _savedBranchId,
        );
        if (mounted) {
          setState(() {
            _isBranchCodeTaken = taken;
            _isCheckingCode = false;
          });
        }
      } catch (_) {
        if (mounted) {
          setState(() {
            _isBranchCodeTaken = false;
            _isCheckingCode = false;
          });
        }
      }
    });
  }

  /// Nạp ảnh base64 (cover + PCCC) từ endpoint riêng khi vào màn SỬA.
  ///
  /// Backend đã `@JsonIgnore` hai cột ảnh nặng để tránh OOM khi trả danh sách,
  /// nên model `branchToEdit` KHÔNG còn ảnh → phải gọi `/images` để lấy.
  Future<void> _loadImagesFromServer(int branchId) async {
    try {
      final repo = ref.read(branchRepositoryProvider);
      final imgs = await repo.getBranchImages(branchId);
      if (!mounted) return;

      final rawCovers = imgs['coverImages'] ?? imgs['coverImage'];
      final covers = _parseImageList(rawCovers);
      final pccc = _parseImageList(imgs['pcccImages']);

      setState(() {
        if (covers.isNotEmpty) _networkCoverPhotos = covers;
        if (pccc.isNotEmpty) {
          _networkPcccPhotos = pccc;
          _hasPccc = true;
        }
      });
    } catch (_) {
      // Không chặn UI nếu tải ảnh lỗi — người dùng vẫn có thể chọn ảnh mới.
    }
  }

  /// Tách chuỗi ảnh (JSON array hoặc chuỗi đơn URL/data-URI) thành List.
  List<String> _parseImageList(String? raw) {
    if (raw == null || raw.trim().isEmpty) return const [];
    final trimmed = raw.trim();
    if (trimmed.startsWith('[')) {
      try {
        final decoded = jsonDecode(trimmed);
        if (decoded is List) {
          return decoded
              .map((e) => e.toString())
              .where((e) => e.isNotEmpty)
              .toList();
        }
      } catch (_) {
        return [trimmed];
      }
    }
    return [trimmed];
  }

