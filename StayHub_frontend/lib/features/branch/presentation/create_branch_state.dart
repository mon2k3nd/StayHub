    }
    // Nếu khôi phục được Tỉnh nhưng thiếu Huyện/Xã (do tên không khớp danh mục),
    // giữ lại cấp còn thiếu từ chi nhánh đã lưu để không làm mất địa chỉ.
    if (widget.branchToEdit != null) {
      if (legalDistrict.isEmpty) {
        legalDistrict = widget.branchToEdit!.legalDistrict ?? '';
      }
      if (legalWard.isEmpty) {
        legalWard = widget.branchToEdit!.legalWard ?? '';
      }
      if (legalProvince.isEmpty) {
        legalProvince = widget.branchToEdit!.legalProvince ?? '';
      }
    }

    final List<String> b64Covers = [];
    try {
      for (final f in _coverPhotos) {
        final bytes = await f.readAsBytes();
        b64Covers.add(base64Encode(bytes));
      }
    } catch (e) {
      _showDialog(
        'Lỗi',
        'Không thể đọc ảnh. Vui lòng thử chọn lại ảnh mặt tiền nhé.',
      );
      return;
    }

    // PCCC: gộp ảnh mới (base64) + ảnh cũ (URL) để không thất thoát khi submit.
    final List<String> b64Pccc = [];
    for (final f in _pcccPhotos) {
      try {
        final bytes = await f.readAsBytes();
        b64Pccc.add(base64Encode(bytes));
      } catch (e) {
        // Không nuốt lỗi im lặng: nếu đọc ảnh thất bại, ảnh PCCC sẽ mất khi lưu.
        debugPrint('[PCCC] Không đọc được ảnh ${f.path}: $e');
      }
    }
    b64Pccc.addAll(_networkPcccPhotos);

    int finalFloors = 1;
    int finalTotalRooms = 1;

    if (_catId != 'NHA_NGUYEN_CAN' && _catId != 'KIOT_BAN_LE') {
      finalFloors = int.tryParse(_floorsCtrl.text) ?? 1;
      int rpf = int.tryParse(_roomsPerFloorCtrl.text) ?? 1;
      finalTotalRooms = finalFloors * rpf;
    }

    int mappedPropertyType =
        kRentalCategories
            .expand((c) => c.subModels)
            .toList()
            .indexWhere((s) => s.id == _subId) +
        1;
    if (mappedPropertyType <= 0) mappedPropertyType = 1;

    // TODO removed: Đã xử lý meta JSON
    Map<String, dynamic> advancedMeta = {
      // ── Địa chỉ có cấu trúc ──────────────────────────────────────────────
      // Lưu kèm ID các cấp để khi "Chỉnh sửa" khôi phục CHÍNH XÁC dropdown
      // (không phụ thuộc việc dò chuỗi addressOld dễ sai).
      'addressMeta': {
        'houseNumber': houseNumber,
        'street': detail,
        'provinceId': _selectedDistrict63Province?['id']?.toString(),
        'provinceName': province63Name,
        'districtId': _selectedDistrict63?['id']?.toString(),
        'districtName': district63Name,
        'wardId': _selectedWard63?['id']?.toString(),
        'wardName': ward63Name,
      },
      'floors': _floors
          .map(
            (f) => {
              'floorNumber': f.floorNumber,
              'rooms': f.rooms
                  .map(
                    (r) => {
                      'tempId': r.tempId,
                      'code': r.code,
                      'subType': r.subType,
                      'isSelfContained': r.isSelfContained,
                      'sharedWcId': r.sharedWcId,
                      'price': r.price,
                      'area': r.area,
                    },
                  )
                  .toList(),
            },
          )
          .toList(),
      'sharedWcs': _sharedWcs
          .map((w) => {'tempId': w.tempId, 'code': w.code, 'name': w.name})
          .toList(),
      'branchAmenities': _selectedAmenities.entries
          .map(
            (e) => {
              'name': e.key,
              'price': e.value['price'] ?? 0.0,
              'chargeType': e.value['chargeType'] ?? 'free',
              'isMandatory': e.value['isMandatory'] ?? true,
            },
          )
          .toList(),
      'customAmenities': _customAmenities,
    };

    setState(() => _isLoading = true);
    try {
      BranchModel? createdBranch;

      final submitData = {
        'branchCode': _autoGeneratedCode,
        'branchName': _nameCtrl.text,
        'address': addressOld, // Backward compat
        'addressOld': addressOld,
        'legalProvince': legalProvince,
        'legalDistrict': legalDistrict,
        'legalWard': legalWard,
        'latitude': _latitude,
        'longitude': _longitude,
        'description': jsonEncode(advancedMeta),
        'pois': _pois.isNotEmpty ? jsonEncode(_pois) : null,
        'propertyType': mappedPropertyType,
        'managementType': 1,
        'numberOfFloors': finalFloors,
        'totalRooms': finalTotalRooms,
        'coverImages': b64Covers.isNotEmpty ? jsonEncode(b64Covers) : null,
        'hasPccc': _hasPccc,
        'pcccImages': b64Pccc.isNotEmpty ? jsonEncode(b64Pccc) : null,
        // Wizard mode: luôn là NHÁP cho tới khi đủ 4 bước. Legacy: ACTIVE.
        'creationStatus': widget.wizardMode ? 'DRAFT' : 'ACTIVE',
        'electricityPrice':
            double.tryParse(
              _elecPriceCtrl.text.replaceAll(',', '').replaceAll('.', ''),
            ) ??
            0,
        'electricityPricingType': 'PER_INDEX',
        'waterPrice':
            double.tryParse(
              _waterPriceCtrl.text.replaceAll(',', '').replaceAll('.', ''),
            ) ??
            0,
        'waterPricingType': _waterUnit == 'Người'
            ? 'PER_PERSON'
            : (_waterUnit == 'Phòng' ? 'PER_ROOM' : 'PER_INDEX'),
        'billingDay': int.tryParse(_billingDayCtrl.text) ?? 1,
        'minLeaseDays': (int.tryParse(_minLeaseDaysCtrl.text) ?? 6) * 30,
        'internetFee': getAmenityFee(
          'Wifi|Internet',
          fallbackCtrl: _internetPriceCtrl,
        ),
        'parkingFee': getAmenityFee(
          'Bãi để xe|Giữ xe|Gửi xe',
          fallbackCtrl: _parkingPriceCtrl,
        ),
        'garbageFee': getAmenityFee(
          'Vệ sinh|Rác',
          fallbackCtrl: _trashPriceCtrl,
        ),
        'petPolicy': _petPolicy == 'CHO_PHEP',
        'roommatePolicy': _roommatePolicy == 'CHO_PHEP',
        'closingTime': _closingTime,
        'cookingPolicy': _cookingPolicy,
        'evChargingAllowed': _evChargingAllowed,
        'evChargeType': _evChargeType,
        'evFixedPrice':
            double.tryParse(
              _evFixedPriceCtrl.text.replaceAll(',', '').replaceAll('.', ''),
            ) ??
            100000,
      };

      if (_savedBranchId != null) {
        // Nháp đã lưu trước đó — UPDATE thay vì create để tránh trùng khoá.
        // Dùng chính BranchModel trả về từ API (giữ đúng cờ step1Done..step4Done
        // của chi nhánh NHÁP) thay vì tra trong danh sách active-only — nếu tra
        // sẽ không thấy nháp và rơi vào placeholder khiến wizard mất trạng thái bước.
        createdBranch = await ref
            .read(branchProvider.notifier)
            .updateBranch(_savedBranchId!, submitData);
        if (createdBranch == null) {
          throw ref.read(branchProvider).error ??
              Exception('Không thể lưu chi nhánh');
        }
      } else {
        // No draft yet - create fresh.
        // Wizard mode dùng API nháp riêng: backend luôn ép DRAFT + reset cờ
        // 4 bước, nên chi nhánh chưa cấu hình xong KHÔNG lên chợ trọ.
        createdBranch = widget.wizardMode
            ? await ref
                  .read(branchProvider.notifier)
                  .createWizardDraft(submitData)
            : await ref.read(branchProvider.notifier).createBranch(submitData);
        if (createdBranch != null) {
          setState(() => _savedBranchId = createdBranch!.id);
        }
      }

      if (mounted) setState(() => _isLoading = false);
      if (createdBranch != null && mounted) {
        // ── WIZARD MODE ──
        // Chỉ trả dữ liệu nền (BranchModel) về cho màn hình wizard để các
        // bước sau dùng làm nền tảng. KHÔNG pushReplacement sang màn hình
        // cấu hình chi tiết, unawaited(tránh thoát khỏi luồng 4 bước.)
        if (widget.wizardMode) {
          // Defer pop ra khỏi frame hiện tại: submit() được gọi từ onTap của
          // GestureDetector, và ToastUtils.show() vừa chèn OverlayEntry +
          // AnimationController ngay trước đó. Gọi Navigator.pop() đồng bộ
          // trong cùng frame khiến Navigator đang bị khoá (_debugLocked) →
          // assertion crash "navigator.dart:3249 !navigator._debugLocked".
          final branchToReturn = createdBranch;
          WidgetsBinding.instance.addPostFrameCallback((_) {
            if (!mounted) return;
            Navigator.of(context).pop(branchToReturn);
          });
          return;
        }

        unawaited(
          ref.read(notificationActionProvider).pushSystemNotification({
            "title": "Tạo dãy trọ thành công!",
            "content":
                "Dãy trọ ${_nameCtrl.text} đã được tạo. Hãy tiếp tục cấu hình.",
            "type": "SYSTEM_ALERT",
            "actionMetadata": jsonEncode({
              "actionUrl": "/owner-dashboard",
              "actionLabel": "Quản lý phòng",
            }),
          }),
        );

        _showDialog(
          'Thành công',
          '🎉 Tạo chi nhánh thành công! Tiếp tục cấu hình từng phòng nhé.',
          isError: false,
          onSuccess: () {
            final branch = createdBranch;
            if (mounted && branch != null) {
              unawaited(
                Navigator.pushReplacement(
                  context,
                  CupertinoPageRoute(
                    builder: (c) => BranchDetailedConfigScreen(
                      branchId: branch.id,
                      branchName: branch.branchName,
                    ),
                  ),
                ),
              );
            }
          },
        );
      } else {
        // createdBranch null → có thể do trùng mã hoặc lỗi API.
        // Hỏi thẳng backend "ai đang giữ mã này" (bao gồm cả chi nhánh đã
        // xóa mềm) để hiển thị đúng thông tin xung đột, thay vì đoán mò
        // từ danh sách branch đang hiển thị (vốn đã bị lọc).
        final codeToCheck = _autoGeneratedCode.isNotEmpty
            ? _autoGeneratedCode
            : _branchCodeCtrl.text;
        Map<String, dynamic>? conflict;
        try {
          conflict = await ref
              .read(branchRemoteDataSourceProvider)
              .checkBranchCodeConflict(codeToCheck, excludeId: _savedBranchId);
        } catch (_) {
          conflict = null;
        }

        if (conflict != null && conflict['taken'] == true && mounted) {
          // BUGFIX (data): coerce an toàn — tránh `as int?`/`as String?` ném
          // TypeError khi backend trả id dạng chuỗi hoặc số cho String.
          final rawConflictingId = conflict['conflictingId'];
          final conflictingId = rawConflictingId is num
              ? rawConflictingId.toInt()
              : int.tryParse(rawConflictingId?.toString() ?? '');
          final conflictingCode = conflict['conflictingCode']?.toString();
          final conflictingName = conflict['conflictingName']?.toString();
          final conflictingStatus = conflict['conflictingStatus']?.toString();

          // Ưu tiên tìm trong danh sách đã tải để có đủ model; nếu không có
          // (ví dụ chi nhánh đã ngừng hoạt động chưa load) thì dựng model tối thiểu.
          final branches = ref.read(branchProvider).value ?? [];
          final existing = branches
              .where((b) => b.id == conflictingId)
              .firstOrNull;

          final conflicting =
              existing ??
              BranchModel(
                id: conflictingId ?? 0,
                ownerId: ref.read(authProvider).value?.id ?? 0,
                branchName: conflictingName ?? 'Chi nhánh khác',
                branchCode: conflictingCode ?? codeToCheck,
                address: '',
                creationStatus: conflictingStatus ?? 'COMPLETED',
              );
          showBranchCodeConflictSheet(conflicting);
        } else {
          final err = ref.read(branchProvider).error;
          _showDialog(
            'Lỗi',
            'Không thể tạo dãy trọ. Vui lòng thử lại.\n\nChi tiết: ${err?.toString() ?? "Không rõ"}',
          );
        }
      }
    } catch (e) {
      if (mounted) setState(() => _isLoading = false);
      // FIX BUG-06/07: Phân loại lỗi để hiển thị thông báo thân thiện thay vì
      // dump raw exception. Luôn kiểm tra mounted trước khi show dialog.
      if (!mounted) return;
      final msg = e.toString().toLowerCase();
      if (msg.contains('401') || msg.contains('unauthorized')) {
        _showDialog(
          'Phiên đăng nhập hết hạn',
          'Vui lòng đăng nhập lại để tiếp tục tạo chi nhánh.',
        );
      } else if (msg.contains('timeout') || msg.contains('timed out')) {
        _showDialog(
          'Kết nối quá chậm',
          'Máy chủ phản hồi quá lâu. Vui lòng kiểm tra mạng và thử lại.',
        );
      } else if (msg.contains('socket') || msg.contains('network')) {
        _showDialog(
          'Mất kết nối',
          'Không thể kết nối máy chủ. Vui lòng kiểm tra mạng và thử lại.',
        );
      } else {
        _showDialog('Lỗi', 'Lỗi không xác định: ${e.toString()}');
      }
    }
  }
}
