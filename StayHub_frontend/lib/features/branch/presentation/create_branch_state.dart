  Future<void> _getCurrentLocation({bool autoPin = true}) async {
    setState(() => _isFetchingLocation = true);
    try {
      LocationPermission permission = await Geolocator.checkPermission();
      if (permission == LocationPermission.denied) {
        permission = await Geolocator.requestPermission();
        if (permission == LocationPermission.denied) {
          if (!mounted) return;
          ToastUtils.show(context, 'Bạn chưa cấp quyền vị trí', isError: true);
          return;
        }
      }
      if (permission == LocationPermission.deniedForever) {
        if (!mounted) return;
        ToastUtils.show(
          context,
          'Quyền vị trí bị từ chối vĩnh viễn',
          isError: true,
        );
        return;
      }

      final position = await Geolocator.getCurrentPosition(
        locationSettings: const LocationSettings(
          accuracy: LocationAccuracy.high,
        ),
      );
      if (mounted) {
        if (autoPin) {
          setState(() {
            _latitude = position.latitude;
            _longitude = position.longitude;
            _isPinned = true;
          });
          _updateProgress();
          unawaited(_fetchPOIs());

          await _reverseGeocode(position.latitude, position.longitude);
          if (mounted) {
            unawaited(HapticFeedback.lightImpact());
            ToastUtils.show(context, 'Đã cập nhật vị trí hiện tại');
            _updateProgress();
            unawaited(_fetchPOIs());
          }
        } else {
          // Just set for map preview without actually pinning
          setState(() {
            _previewLat = position.latitude;
            _previewLon = position.longitude;
          });
        }
      }
    } catch (e) {
      if (mounted) ToastUtils.show(context, 'Lỗi vị trí: $e', isError: true);
    } finally {
      if (mounted) setState(() => _isFetchingLocation = false);
    }
  }

  // ─── Mở Map Picker fullscreen ───────────────────────────────────────────
  Future<void> _openMapPicker() async {
    unawaited(HapticFeedback.selectionClick());

    final fallbackTitleParts = <String>[];
    if (_selectedWard63 != null) {
      fallbackTitleParts.add(_selectedWard63!['name']);
    }
    if (_selectedDistrict63 != null) {
      fallbackTitleParts.add(_selectedDistrict63!['name']);
    }
    if (_selectedDistrict63Province != null) {
