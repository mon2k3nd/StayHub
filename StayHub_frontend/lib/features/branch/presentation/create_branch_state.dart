    if (_houseNumberCtrl.text.trim().isNotEmpty) {
      fallbackSubtitleParts.add(_houseNumberCtrl.text.trim());
    }
    if (_addressDetailCtrl.text.trim().isNotEmpty) {
      fallbackSubtitleParts.add(_addressDetailCtrl.text.trim());
    }
    if (fallbackTitleParts.isNotEmpty) {
      fallbackSubtitleParts.add(fallbackTitleParts.join(', '));
    }

    final initialLat = _latitude ?? _previewLat;
    final initialLon = _longitude ?? _previewLon;

    final result = await showDialog<MapPickResult>(
      context: context,
      builder: (_) => MapPickerDialog(
        initialLat: initialLat,
        initialLon: initialLon,
        fallbackAddressTitle: fallbackTitleParts.isNotEmpty
            ? fallbackTitleParts.join(', ')
            : null,
        fallbackAddressSubtitle: fallbackSubtitleParts.isNotEmpty
            ? fallbackSubtitleParts.join(', ')
            : null,
        formWardName: _selectedWard63?['name'],
        formDistrictName: _selectedDistrict63?['name'],
        formProvinceName: _selectedDistrict63Province?['name'],
      ),
    );
    if (result == null || !mounted) {
      // Case 2: Đóng map mà chưa ghim
      if (result == null && mounted && _latitude == null) {
        ToastUtils.show(
          context,
          'Bạn chưa ghim vị trí — chưa thể lưu bất động sản này!',
        );
      }
      return;
    }

    // Case 4: Validate toạ độ trong lãnh thổ Việt Nam
    const double vnLatMin = 8.5, vnLatMax = 23.4;
    const double vnLonMin = 102.1, vnLonMax = 109.5;
    final lat = result.latLng.latitude;
    final lon = result.latLng.longitude;
    if (lat < vnLatMin || lat > vnLatMax || lon < vnLonMin || lon > vnLonMax) {
      if (mounted) {
        unawaited(
          showCupertinoDialog(
            context: context,
            builder: (ctx) => CupertinoAlertDialog(
              title: const Text('Vị trí ngoài Việt Nam'),
              content: const Text(
                'Chấm ghim nằm ngoài lãnh thổ Việt Nam. '
                'StayHub chỉ hỗ trợ bất động sản trong nước. '
                'Vui lòng ghìm lại đúng vị trí.',
              ),
              actions: [
                CupertinoDialogAction(
                  isDefaultAction: true,
                  onPressed: () {
                    Navigator.pop(ctx);
                    unawaited(_openMapPicker());
                  },
                  child: const Text('Ghim lại'),
                ),
              ],
            ),
          ),
        );
      }
      return;
    }

    setState(() {
      _latitude = result.latLng.latitude;
      _longitude = result.latLng.longitude;
      _isPinned = true;
      _isFetchingLocation = true;
      // Fill street name if available and not yet filled by user
      if (result.street != null &&
          result.street!.isNotEmpty &&
          _addressDetailCtrl.text.isEmpty) {
        String streetToFill = result.street!;
        final lowerStreet = OsmMapService.normalize(streetToFill);

        // Cố gắng khôi phục dấu tiếng Việt nếu tên đường trùng với tên Quận/Phường
        if (_selectedDistrict63 != null) {
          final distName = _selectedDistrict63!['name']?.toString() ?? '';
          if (OsmMapService.normalize(distName) == lowerStreet) {
            streetToFill = distName;
          }
        }
        if (_selectedWard63 != null) {
          final wardName = _selectedWard63!['name']?.toString() ?? '';
          if (OsmMapService.normalize(wardName) == lowerStreet) {
            streetToFill = wardName;
          }
        }

        _addressDetailCtrl.text = streetToFill;
      }
    });
    _updateProgress();
    unawaited(_fetchPOIs());

    final bool isUnmoved =
        (result.latLng.latitude == initialLat &&
        result.latLng.longitude == initialLon);

    if (isUnmoved) {
      if (!mounted) return;
      setState(() => _isFetchingLocation = false);
      ToastUtils.show(context, 'Đã ghim vị trí ✅');
      return;
    }

    // Full address mapping via esgoo
    await _reverseGeocode(
      result.latLng.latitude,
      result.latLng.longitude,
      osmWard: result.ward,
      osmDistrict: result.district,
      osmProvince: result.province,
    );

    if (!mounted) return;
    setState(() => _isFetchingLocation = false);
    ToastUtils.show(context, 'Đã ghim vị trí ✅');
  }

