          return false;
        }
      }

      if (_houseNumberCtrl.text.trim().isEmpty) {
        _showDialog('Lỗi', 'Vui lòng nhập số nhà, ngõ ngách');
        return false;
      }

      if (_addressDetailCtrl.text.trim().isEmpty) {
        _showDialog('Lỗi', 'Vui lòng nhập tên đường');
        return false;
      }

      // FIX BUG-05: Bắt buộc phải GHIM thật (_isPinned) — không chỉ có toạ độ
      // từ geocode gợi ý, tránh submit với vị trí chưa được xác nhận.
      if (_latitude == null || _longitude == null || !_isPinned) {
        _showDialog('Lỗi', 'Vui lòng gim vị trí chính xác trên bản đồ');
        return false;
      }

      if (_coverPhotos.isEmpty && _networkCoverPhotos.isEmpty) {
        _showDialog('Lỗi', 'Vui lòng chọn ít nhất 1 ảnh mặt tiền');
        return false;
      }
    } else if (_currentStep == 1) {
      // Validate mô hình kinh doanh
      if (_catId.isEmpty || _subId.isEmpty) {
        _showDialog('Lỗi', 'Vui lòng chọn mô hình bất động sản');
        return false;
      }
      // Validate số tầng nếu mô hình vận hành theo phòng
      if (rentalCategoryById(_catId)?.isRoomBased ?? false) {
        final floors = int.tryParse(_floorsCtrl.text.trim());
        if (floors == null || floors < 1) {
          _showDialog('Lỗi', 'Vui lòng nhập số tầng (tối thiểu 1)');
          return false;
        }
      }
    } else if (_currentStep == 2) {
      // Chỉ validate số tầng/phòng với mô hình vận hành theo phòng
      if (rentalCategoryById(_catId)?.isRoomBased ?? false) {
        final floors = int.tryParse(_floorsCtrl.text);
        final rpf = int.tryParse(_roomsPerFloorCtrl.text);
        if (floors == null || floors < 1) {
          _showDialog('Lỗi', 'Vui lòng nhập đúng số tầng (tối thiểu 1)');
          return false;
        }
        if (rpf == null || rpf < 1) {
          _showDialog(
            'Lỗi',
            'Vui lòng nhập đúng số phòng mỗi tầng (tối thiểu 1)',
          );
          return false;
        }

        // Validate all generated rooms to ensure price and area are entered
        for (var f in _floors) {
          for (var r in f.rooms) {
            // Use the human-readable room code (e.g. "P101") instead of the
            // internal tempId so the landlord knows exactly which room to fix.
            final roomLabel = r.code.isNotEmpty
                ? r.code
                : 'Tầng ${f.floorNumber}';
            if (r.price <= 0 || r.area <= 0) {
              _showDialog(
                'Lỗi',
                'Vui lòng điền Giá thuê và Diện tích lớn hơn 0 cho tất cả các phòng (Thiếu thông tin ở phòng $roomLabel)',
              );
              return false;
            }
            // Edge case: guard against absurd values caused by a mistyped
            // currency amount (e.g. an extra zero) or a corrupted area.
            if (r.price > 1000000000) {
              _showDialog(
                'Lỗi',
                'Giá thuê của phòng $roomLabel quá lớn (tối đa 1 tỷ VNĐ). Vui lòng kiểm tra lại.',
              );
              return false;
            }
            if (r.area > 1000) {
              _showDialog(
                'Lỗi',
                'Diện tích của phòng $roomLabel quá lớn (tối đa 1000 m²). Vui lòng kiểm tra lại.',
              );
              return false;
            }
          }
        }
      }
    } else if (_currentStep == 3) {
      if (_elecPriceCtrl.text.isEmpty) {
        _showDialog('Lỗi', 'Vui lòng nhập giá điện');
        return false;
      }
      if (_waterPriceCtrl.text.isEmpty) {
        _showDialog('Lỗi', 'Vui lòng nhập giá nước');
        return false;
      }
      // Edge case: electricity/water unit prices are per kWh/m³ and should be
      // within a sane range. A mistyped extra zero would otherwise be accepted.
      final elecPrice =
          double.tryParse(
            _elecPriceCtrl.text.replaceAll(',', '').replaceAll('.', ''),
          ) ??
          0;
      final waterPrice =
          double.tryParse(
            _waterPriceCtrl.text.replaceAll(',', '').replaceAll('.', ''),
          ) ??
          0;
      if (elecPrice <= 0) {
        _showDialog('Lỗi', 'Giá điện phải lớn hơn 0');
        return false;
      }
      if (waterPrice <= 0) {
        _showDialog('Lỗi', 'Giá nước phải lớn hơn 0');
        return false;
      }
      if (elecPrice > 100000) {
        _showDialog(
          'Lỗi',
          'Giá điện quá cao (tối đa 100.000đ/kWh). Vui lòng kiểm tra lại.',
        );
        return false;
      }
      if (waterPrice > 500000) {
        _showDialog(
          'Lỗi',
          'Giá nước quá cao (tối đa 500.000đ). Vui lòng kiểm tra lại.',
        );
        return false;
      }
    }
    return true;
  }

