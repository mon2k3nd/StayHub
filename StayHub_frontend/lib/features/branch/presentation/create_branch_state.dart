  Future<void> _fetchProvinces() async {
    try {
      final res = await ApiClient()
          .get('/api/v1/addresses/provinces')
          .timeout(const Duration(seconds: 2));
      if (mounted) {
        // BUGFIX (data): tránh `as List` ném TypeError khi `data` là null/không
        // phải List — lọc an toàn bằng whereType.
        final raw = res['data'];
        setState(
          () => _provinces = raw is List
              ? raw
                    .whereType<Map>()
                    .map((e) => Map<String, dynamic>.from(e))
                    .toList()
              : <Map<String, dynamic>>[],
        );
      }
    } on TimeoutException {
      debugPrint('Fetch provinces timeout — using local fallback');
    } catch (e) {
      debugPrint('Fetch provinces error: $e');
    }
  }

  /// Khôi phục Tỉnh/Huyện/Xã từ tên đã lưu trên model (legalProvince/…).
  Future<bool> _restoreAddressFromMeta(BranchModel b) async {
    final provName = b.legalProvince?.trim() ?? '';
    final distName = b.legalDistrict?.trim() ?? '';
    final wardName = b.legalWard?.trim() ?? '';
    if (provName.isEmpty) return false;

    final prov = AddressMappingService.findEsgooProvince(provName, _provinces);
    if (prov == null) return false;
    _selectedDistrict63Province = prov;

    if (distName.isEmpty) return true;
    await _fetchDistricts63(prov['id'].toString());
    final dist = AddressMappingService.findBestMatch(distName, _districts63);
    if (dist == null) return true;
    _selectedDistrict63 = dist;

    if (wardName.isEmpty) return true;
    await _fetchWards63(dist['id'].toString());
    final ward = AddressMappingService.findBestMatch(wardName, _wards63);
    if (ward != null) _selectedWard63 = ward;
    return true;
  }

  /// Khôi phục địa chỉ từ chuỗi `addressOld` của chi nhánh đang chỉnh sửa.
  Future<void> _restoreAddressFromBranch() async {
    final b = widget.branchToEdit;
    if (b == null) return;

    // Ưu tiên tên cấp hành chính đã lưu trên model trước khi parse chuỗi.
    if (await _restoreAddressFromMeta(b)) {
      if (mounted) setState(() {});
      return;
    }

    final raw = (b.addressOld?.trim().isNotEmpty ?? false)
        ? b.addressOld!.trim()
        : b.address.trim();
    if (raw.isEmpty) return;

    // Tách chuỗi "Số nhà, Tên đường, Phường, Quận, Tỉnh" từ phải sang trái.
    final parts = raw
        .split(',')
        .map((e) => e.trim())
        .where((e) => e.isNotEmpty)
        .toList();
    if (parts.length < 3) return;

    final provinceName = parts[parts.length - 1];
    final districtName = parts[parts.length - 2];
    final wardName = parts[parts.length - 3];

    // Tìm tỉnh khớp (bỏ tiền tố "Tỉnh"/"Thành phố").
    final prov = AddressMappingService.findEsgooProvince(
      provinceName,
      _provinces,
    );
    if (prov == null) return;
    _selectedDistrict63Province = prov;

    await _fetchDistricts63(prov['id'].toString());
    final dist = AddressMappingService.findBestMatch(
      districtName,
      _districts63,
    );
    if (dist == null) return;
    _selectedDistrict63 = dist;

    await _fetchWards63(dist['id'].toString());
    final ward = AddressMappingService.findBestMatch(wardName, _wards63);
    if (ward != null) _selectedWard63 = ward;

    // Phần còn lại là số nhà + tên đường.
    final rest = parts.sublist(0, parts.length - 3);
    if (rest.isNotEmpty) {
      _houseNumberCtrl.text = rest.first;
      if (rest.length > 1) {
        _addressDetailCtrl.text = rest.sublist(1).join(', ');
      }
    }

    if (mounted) setState(() {});
  }

