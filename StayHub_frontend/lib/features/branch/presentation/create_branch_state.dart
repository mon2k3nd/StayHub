  Future<void> _reverseGeocode(
    double lat,
    double lon, {
    String? osmWard,
    String? osmDistrict,
    String? osmProvince,
  }) async {
    try {
      // Use provided OSM strings (from picker) or call network
      String wardStr = osmWard ?? '';
      String districtStr = osmDistrict ?? '';
      String provinceStr = osmProvince ?? '';

      // Ensure raw OSM province is immediately mapped back to old-63 if needed
      if (provinceStr.isNotEmpty) {
        provinceStr = OsmMapService.resolveOld63Province(
          provinceStr,
          districtStr,
        );
      }

      String displayStr = '';

      if (wardStr.isEmpty || districtStr.isEmpty || provinceStr.isEmpty) {
        final osmService = ref.read(osmMapServiceProvider);
        final osmAddr = await osmService.reverseGeocode(lat, lon);
        if (osmAddr == null) return;
        wardStr = wardStr.isEmpty ? (osmAddr.ward ?? '') : wardStr;
        districtStr = districtStr.isEmpty
            ? (osmAddr.district ?? '')
            : districtStr;
        provinceStr = provinceStr.isEmpty
            ? (osmAddr.province ?? '')
            : provinceStr;
        displayStr = osmAddr.displayAddress;

        // Fill street/house only if not yet filled
        if (!mounted) return;
        if (_addressDetailCtrl.text.trim().isEmpty) {
          String streetToFill = osmAddr.street?.trim() ?? '';
          if (streetToFill.isNotEmpty) {
            final lowerStreet = OsmMapService.normalize(streetToFill);

            if (_selectedDistrict63 != null) {
              final distName = _selectedDistrict63!['name']?.toString() ?? '';
              if (OsmMapService.normalize(distName) == lowerStreet) {
                streetToFill = distName;
              }
            }
            if (_selectedWard63 != null) {
              final wardName = _selectedWard63!['name']?.toString() ?? '';
              if (OsmMapService.normalize(wardName) == lowerStreet) {
                streetToFill = wardName;
              }
            }
            _addressDetailCtrl.text = streetToFill;
          }
        }
      }

      // ── Province resolution ───────────────────────────────────────────────
      // OSM may return new merged province names (e.g. "Ninh Bình" for a pin
      // actually inside old "Nam Định"). We always try the user's already-selected
      // old-63 province FIRST. Only fall back to OSM-matched province if the
      // district cannot be found in the selected province.
      Map<String, dynamic>? matchedProv =
          AddressMappingService.findEsgooProvince(
            provinceStr.isNotEmpty ? provinceStr : displayStr,
            _provinces,
          );

      // Anchor to the form's already-selected province when district lookup
      // will tell us more accurately which old-63 province the pin is in.
      final anchorProvince = _selectedDistrict63Province ?? matchedProv;

      Map<String, dynamic>? matchedDist;
      List<Map<String, dynamic>> tempDistricts = [];

      // Step A: try finding district in the SELECTED (form) province first.
      if (anchorProvince != null) {
        try {
          final dRes = await ApiClient()
              .get('/api/v1/addresses/districts/${anchorProvince['id']}')
              .timeout(const Duration(seconds: 2));
          final candidateDistricts = (dRes['data'] as List? ?? [])
              .cast<Map<String, dynamic>>();
          final candidateDist = AddressMappingService.findBestMatch(
            districtStr,
            candidateDistricts,
            fallbackAddress: displayStr,
          );
          if (candidateDist != null) {
            // District found in selected province → OSM province string is
            // unreliable (new merged name); trust the form province.
            matchedProv = anchorProvince;
            tempDistricts = candidateDistricts;
            matchedDist = candidateDist;
          }
        } catch (_) {}
      }

      // Step B: fallback — district not found in selected province, try OSM province.
      if (matchedDist == null &&
          matchedProv != null &&
          matchedProv['id'] != anchorProvince?['id']) {
        try {
          final dRes = await ApiClient()
              .get('/api/v1/addresses/districts/${matchedProv['id']}')
              .timeout(const Duration(seconds: 2));
          tempDistricts = (dRes['data'] as List? ?? [])
              .cast<Map<String, dynamic>>();
          matchedDist = AddressMappingService.findBestMatch(
            districtStr,
            tempDistricts,
            fallbackAddress: displayStr,
          );
        } catch (_) {}
      }

      Map<String, dynamic>? matchedWard;
      List<Map<String, dynamic>> tempWards = [];
      if (matchedDist != null) {
        try {
          final wRes = await ApiClient()
              .get('/api/v1/addresses/wards/${matchedDist['id']}')
              .timeout(const Duration(seconds: 2));
          tempWards = (wRes['data'] as List? ?? [])
              .cast<Map<String, dynamic>>();
          matchedWard = AddressMappingService.findBestMatch(
            wardStr,
            tempWards,
            fallbackAddress: displayStr,
          );
        } catch (_) {}
      }

      if (!mounted) return;

      // ── Resolve Merged Province Ambiguity ───────────────────────────────
      // If the map returned a province that belongs to the SAME new-34 province
      // as the user's form selection, we trust the user's selection.
      // This prevents conflicts where OSM returns "Ninh Bình" (merged) for a pin
      // that is actually in "Nam Định", but OSM lacks district data to disambiguate.
      if (_selectedDistrict63Province != null && matchedProv != null) {
        final formNew34 = AddressData.getNew34ByEsgooId(
          _selectedDistrict63Province!['id'],
        );
        final mapNew34 = AddressData.getNew34ByEsgooId(matchedProv['id']);
        if (formNew34 != null &&
            mapNew34 != null &&
            formNew34['id'] == mapNew34['id']) {
          matchedProv = _selectedDistrict63Province;
        }
      }

      bool isConflict = false;
      if (_selectedDistrict63Province != null && matchedProv != null) {
        if (_selectedDistrict63Province!['id'] != matchedProv['id']) {
          isConflict = true;
        } else if (_selectedDistrict63 != null && matchedDist != null) {
          if (_selectedDistrict63!['id'] != matchedDist['id']) {
            isConflict = true;
          } else if (_selectedWard63 != null && matchedWard != null) {
            if (_selectedWard63!['id'] != matchedWard['id']) {
              isConflict = true;
            }
          }
        }
      }

      if (isConflict) {
        _showPinConflictDialog(
          matchedProv,
          matchedDist,
          matchedWard,
          tempDistricts,
          tempWards,
        );
        return;
      }

      setState(() {
        final fromPicker = osmProvince != null;
        if (fromPicker || _selectedDistrict63Province == null) {
          if (matchedProv != null) {
            // Chỉ cập nhật Province nếu khác với cái user đã chọn
            _selectedDistrict63Province = matchedProv;

            // Chỉ cập nhật Districts nếu load được danh sách mới
            if (tempDistricts.isNotEmpty) {
              _districts63 = tempDistricts;
            }

            // Chỉ ghi đè District nếu OSM match được — không xóa nếu user đã chọn sẵn
            if (matchedDist != null) {
              _selectedDistrict63 = matchedDist;

              // Chỉ cập nhật Wards nếu load được danh sách mới
              if (tempWards.isNotEmpty) {
                _wards63 = tempWards;
              }

              // Chỉ ghi đè Ward nếu OSM match được — không xóa nếu user đã chọn sẵn
              if (matchedWard != null) {
                _selectedWard63 = matchedWard;
              }
            }
          }
        }
      });
      // Green box uses _getNewProvinceName() directly in step1_info_widget
    } catch (e, st) {
      debugPrint('Lỗi reverse geocode: $e\n$st');
    }
  }

