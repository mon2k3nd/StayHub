  String _formatCurrency(double amount) {
    if (amount <= 0) return '0đ';
    final formatted = amount
        .toStringAsFixed(0)
        .replaceAllMapped(RegExp(r'(\d)(?=(\d{3})+(?!\d))'), (m) => '${m[1]}.');
    return '$formattedđ';
  }

  Future<void> _fetchPOIs({bool isSilent = false}) async {
    if (!isSilent) setState(() => _isLoadingPOIs = true);

    final String ward63Name =
        _selectedWard63?['full_name'] ?? _selectedWard63?['name'] ?? '';
    final String dist63Name =
        _selectedDistrict63?['full_name'] ?? _selectedDistrict63?['name'] ?? '';
    String prov63Name =
        _selectedDistrict63Province?['full_name'] ??
        _selectedDistrict63Province?['name'] ??
        '';
    if (prov63Name.isEmpty && _selectedDistrict63Province != null) {
      final rawId = _selectedDistrict63Province!['id']?.toString() ?? '';
      for (final tryId in [rawId, rawId.padLeft(2, '0')]) {
        final lp = AddressData.getProvinces63Sorted().firstWhere(
          (p) => p['id']?.toString() == tryId,
          orElse: () => <String, dynamic>{},
        );
        prov63Name = lp['full_name'] ?? lp['name'] ?? '';
        if (prov63Name.isNotEmpty) break;
      }
    }

    if (_latitude == null || _longitude == null) {
      LatLng? latLng;
      try {
        final osm = ref.read(osmMapServiceProvider);
        // Structured search — tránh fuzzy match sai tỉnh
        if (prov63Name.isNotEmpty) {
          final geocodeResult = await osm.geocodeVietnamese(
            ward: ward63Name.isNotEmpty ? ward63Name : null,
            district: dist63Name.isNotEmpty ? dist63Name : null,
            province: prov63Name,
          );
          latLng = geocodeResult?.latLng;
        }

        // FIX BUG-02: Geocode chỉ dùng để GỢI Ý vị trí xem trước, KHÔNG được
        // coi là đã ghim. Chỉ gán preview + setState, tuyệt đối không set
        // _isPinned = true để tránh submit pass validation khi chưa ghim.
        if (latLng != null) {
          _previewLat = latLng.latitude;
          _previewLon = latLng.longitude;
          if (mounted) setState(() {});
        }
      } catch (e) {
        debugPrint('Error in geocoding branch coordinates: $e');
      }

      if (_latitude == null || _longitude == null) {
        if (mounted) {
          setState(() {
            _isLoadingPOIs = false;
            _hasFetchedPOIs = true;
          });
        }
        return; // Skip POI fetching if we can't find coords
      }
    }

    try {
      final results = await ref
          .read(osmMapServiceProvider)
          .fetchNearbyPOIs(_latitude!, _longitude!, radius: 1000);

      if (mounted) {
        setState(() {
          _pois = results;
          _hasFetchedPOIs = true;
          _isLoadingPOIs = false;
        });
      }
    } catch (e) {
      if (mounted) {
        setState(() {
          _pois = [];
          _isLoadingPOIs = false;
          _hasFetchedPOIs = true;
        });
        // We removed the intrusive Toast here because POIs are non-critical.
        // The user will simply see the empty state "Không tìm thấy tiện ích nào gần đây"
        // and can manually add them if needed.
      }
    }
  }

