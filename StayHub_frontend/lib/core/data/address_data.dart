  static String getNewWardName(String oldWard, String oldDistrict) {
    if (oldWard.isEmpty && oldDistrict.isEmpty) return '';

    // Chuẩn hoá để dò tìm
    final wClean = oldWard
        .toLowerCase()
        .replaceFirst('phường', '')
        .replaceFirst('xã', '')
        .trim();
    final dClean = oldDistrict
        .toLowerCase()
        .replaceFirst('quận', '')
        .replaceFirst('huyện', '')
        .trim();
    final key = '$wClean|$dClean';

    if (wardMergerMap.containsKey(key)) {
      return wardMergerMap[key]!;
    }

    // Mặc định nếu chưa có trong bảng map thì tự động ghép tên Phường - Quận (để không bị mất dữ liệu Quận cũ)
    if (oldWard.isNotEmpty && oldDistrict.isNotEmpty) {
      return '$oldWard - $oldDistrict';
    }

    return oldWard.isNotEmpty ? oldWard : oldDistrict;
  }
